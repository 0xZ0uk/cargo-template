/** An icon picked with the `icon` field. Renders nothing for an empty or unknown name. */
export const Icon: React.FC<{ name?: string | null } & LucideProps> = ({ name, ...props }) => {
  const Component = name ? icons[name as IconName] : undefined
  return Component ? <Component aria-hidden="true" {...props} /> : null
}
